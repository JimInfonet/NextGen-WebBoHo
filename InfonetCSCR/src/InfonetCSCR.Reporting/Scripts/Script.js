function formatMoney(val) {
    conv = val.toLocaleString('en-US', {
        style: 'currency',
        currency: 'USD',
    });
    return conv;
}

function formatQty(val) {
    conv = val.toFixed(2).toLocaleString('en-US', {
        style: 'decimal',
    });
    return conv;
}

